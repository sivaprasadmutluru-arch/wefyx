create table if not exists shop_offers (
 id bigint generated by default as identity primary key,
 code varchar(40) not null unique,
 title varchar(160) not null,
 discount_type varchar(255) not null,
 discount_value numeric(14,2) not null,
 minimum_subtotal numeric(14,2) not null default 0,
 maximum_discount numeric(14,2),
 mode varchar(255) not null,
 starts_on date,
 ends_on date,
 active boolean not null default false
);
create table if not exists shop_offer_products (
 offer_id bigint not null references shop_offers(id),
 product_code varchar(255) not null,
 primary key(offer_id,product_code)
);
alter table if exists customer_orders add column if not exists promo_code varchar(40);
alter table if exists customer_orders add column if not exists discount_amount numeric(14,2) default 0;
